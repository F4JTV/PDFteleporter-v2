const Translation *translation_for(const std::string &font_name) {
    static const Translation wingdings = private_table(kWingdings);
    static const Translation symbol = [] {
        Translation t = private_table(kSymbol);
        return t;
    }();
    std::u32string name = py::to_u32(font_name);
    size_t plus = name.find(U'+');
    if (plus != std::u32string::npos)
        name = name.substr(plus + 1);
    if (matches_wingdings(name))
        return &wingdings;
    if (matches_symbol(name))
        return &symbol;
    return nullptr;
}

std::u32string translate(const std::u32string &text, const Translation &table) {
    std::u32string out;
    out.reserve(text.size());
    for (char32_t c : text) {
        auto found = table.find(c);
        out += found == table.end() ? c : found->second;
    }
    return out;
}

