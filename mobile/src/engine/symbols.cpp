// The table keyed by the private-use codes MuPDF reports, U+F020 and up.
template <size_t N>
Translation private_table(const std::pair<char32_t, char32_t> (&table)[N]) {
    Translation out;
    for (const auto &[code, ch] : table)
        out[0xF000 + code] = ch;
    return out;
}

bool word_char(char32_t c) {
    // Python's \w: letters, digits, the numerics of Latin-1, and "_".
    return c == U'_' || (c >= U'0' && c <= U'9') || py::isalpha(c) || c == 0xB2 || c == 0xB3 || c == 0xB9 ||
           c == 0xBC || c == 0xBD || c == 0xBE;
}

bool is_space(char32_t c) { return py::isspace(c); }

char32_t fold(char32_t c) { return (c >= U'A' && c <= U'Z') ? c + 32 : c; }

// re.match(r"wingdings(?![\s_-]*[23])", name, re.IGNORECASE)
bool matches_wingdings(const std::u32string &name) {
    static const std::u32string word = U"wingdings";
    if (name.size() < word.size())
        return false;
    for (size_t i = 0; i < word.size(); ++i)
        if (fold(name[i]) != word[i])
            return false;
    size_t i = word.size();
    while (i < name.size() && (is_space(name[i]) || name[i] == U'_' || name[i] == U'-'))
        ++i;
    return !(i < name.size() && (name[i] == U'2' || name[i] == U'3'));
}

// re.match(r"symbol(?:mt)?\b", name, re.IGNORECASE)
bool matches_symbol(const std::u32string &name) {
    static const std::u32string word = U"symbol";
    if (name.size() < word.size())
        return false;
    for (size_t i = 0; i < word.size(); ++i)
        if (fold(name[i]) != word[i])
            return false;
    auto boundary = [&](size_t at) { return at >= name.size() || !word_char(name[at]); };
    size_t at = word.size();
    if (name.size() >= at + 2 && fold(name[at]) == U'm' && fold(name[at + 1]) == U't' && boundary(at + 2))
        return true;
    return boundary(at);
}

