"""Write qml/IconPaths.js: the path data of the Material Icons the interface
draws (Google, Apache License 2.0), so that no image file is needed and every
icon takes the colours of the palette.

    git clone --depth 1 https://github.com/google/material-design-icons mdi
    python3 tools/make_icon_paths.py mdi/src qml/IconPaths.js

The first argument is the "src" folder of that repository, or a folder with
the 24px SVG files directly, named after the icons.
"""
import pathlib
import sys
import xml.etree.ElementTree as ET

# Name used by the interface -> Material Icons file name.
WANTED = {
    "pdf": "picture_as_pdf", "folder": "folder_open", "archive": "archive",
    "unarchive": "unarchive", "share": "share", "save": "save_alt",
    "open": "open_in_new", "copy": "content_copy", "clear": "delete_sweep",
    "more": "more_vert", "close": "close", "info": "info", "palette": "palette",
    "light": "light_mode", "dark": "dark_mode", "night": "nightlight",
    "warning": "warning", "success": "check_circle", "error": "error",
    "time": "schedule", "antenna": "settings_input_antenna", "document": "description",
    "log": "article", "rebuild": "restore_page", "image": "image",
    "copyright": "copyright", "code": "code", "check": "check", "send": "send",
    "upload": "upload_file", "compress": "compress", "tune": "tune",
    "text": "text_format", "hourglass": "hourglass_empty",
}

folder = pathlib.Path(sys.argv[1])


def svg_of(name: str) -> pathlib.Path:
    """The 24px "filled" SVG of an icon, in either layout of the folder."""
    flat = folder / f"{name}.svg"
    if flat.exists():
        return flat
    found = sorted(folder.glob(f"*/{name}/materialicons/24px.svg"))
    if not found:
        raise SystemExit(f"{name}: no SVG under {folder}")
    return found[0]


# ".pragma library" first: Qt's CMake looks for it in the first 128 bytes
# only, and warns when it is not there.
out = [".pragma library",
       "// Material Icons by Google (Apache License 2.0), 24x24 view box.",
       "// Generated by tools/make_icon_paths.py; path data unchanged.",
       "", "var paths = {"]
for name, file in sorted(WANTED.items()):
    root = ET.parse(svg_of(file)).getroot()
    assert root.get("viewBox") == "0 0 24 24", file
    parts = []
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        if tag in ("svg", "g"):
            assert not el.get("transform"), file
            continue
        if el.get("fill") == "none":
            continue
        if tag != "path":
            raise SystemExit(f"{file}: unsupported <{tag}>")
        parts.append(el.get("d").strip())
    out.append(f'    "{name}": "{" ".join(parts)}",')
out[-1] = out[-1].rstrip(",")
out += ["};", ""]
pathlib.Path(sys.argv[2]).write_text("\n".join(out), encoding="utf-8")
print(len(WANTED), "icons")
